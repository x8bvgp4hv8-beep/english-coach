/**
 * Как из слова получается имя файла озвучки — одно правило на приложение и на генератор.
 *
 * Правило лежало в трёх копиях: в `speech.ts`, в `scripts/build-voice.mjs` и в тестах.
 * Копии расходятся молча: несовпадение имени не ломает сборку и не пишет в консоль, оно
 * просто отправляет слово в системный синтез — человек выбирает голос и слышит не его.
 *
 * Пунктуация снимается не для красоты: образец голоса в настройках звучит как «Hello!»,
 * а файл называется `hello.opus`, и одного восклицательного знака хватало, чтобы
 * приветствие читал робот.
 */
export const voiceFileName = (word: string): string =>
  word.toLowerCase().trim().replace(/[.!?,;:¡¿]/g, '').replace(/\s+/g, '-').replace(/'/g, '')

/** Путь к файлу слова относительно корня сборки — тот же, что кладёт генератор. */
export const voiceWordPath = (word: string, language: string, gender: 'male' | 'female'): string =>
  `voice/${language}/${gender}/${voiceFileName(word)}.opus`
